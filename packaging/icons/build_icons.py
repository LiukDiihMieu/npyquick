"""Generate every npyquick icon and logo file from one master SVG.

    python packaging/icons/build_icons.py

Reads the two master files next to this script and rewrites the files listed
in ``main()``. The outputs are committed, so run this after editing the master
(or the colours below) and commit the result. Needs only PySide6, which
npyquick already depends on.

Three kinds of output:

* README logos: the mark plus the wordmark, in a light and a dark theme.
* The bare mark, in a light and a dark theme.
* The application icon: the mark on a rounded plate. An app icon cannot follow
  the desktop theme, and the bare mark loses its brackets on a dark dock or
  taskbar, so the plate gives it its own background. Rendered to the PNG and
  ICO files the AppImage, Snap and Windows packages ship.

``icon-small-master.svg`` is a simplified application icon (brackets around a
2 x 2 matrix). The full icon is unreadable below about 32 px, so the smallest
entries of the .ico use this one instead.
"""

from __future__ import annotations

import copy
import os
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QRectF, Qt
from PySide6.QtGui import QGuiApplication, QImage, QPainter
from PySide6.QtSvg import QSvgRenderer

REPO = Path(__file__).resolve().parents[2]
MASTER = Path(__file__).with_name("logo-master.svg")
SMALL_MASTER = Path(__file__).with_name("icon-small-master.svg")

SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)

GENERATED_NOTE = (
    "<!-- Generated by packaging/icons/build_icons.py from the master SVGs in "
    "packaging/icons/. Do not edit by hand. -->\n"
)

# ----------------------------------------------------------------------
# Colours. Each shape in a master carries a data-role naming one of these;
# a role ending in "-stroke" colours the outline instead of the fill.
# ----------------------------------------------------------------------

LIGHT = {
    "brace": "#1f2d44",    # array brackets, and "quick" in the wordmark
    "cell": "#e6e6e6",     # grid cells
    "fox": "#fe721b",      # fox body, and "npy" in the wordmark
    "white": "#ffffff",    # bib and tail tip
    "detail": "#1f2d44",   # eyes and nose
    "tagline": "#a8a8a8",
}
DARK = {**LIGHT, "brace": "#e6edf3", "cell": "#444c56", "white": "#e6edf3", "detail": "#2b3a55"}
APP_ICON = {**LIGHT, "cell": "#f3dcc4", "plate": "#fff3e6", "plate-border": "#ecd3b8"}
# The small icon's cells are darker: at 16 px the pale ones vanish into the plate.
APP_ICON_SMALL = {**APP_ICON, "cell": "#e8c9a6"}

# ----------------------------------------------------------------------
# Geometry, in the master's coordinates (a 1700 x 600 canvas).
# ----------------------------------------------------------------------

LOGO_BOX = (0.0, 0.0, 1700.0, 600.0)                 # x, y, width, height
MARK_BOX = (89.824, 72.861, 515.264, 454.277)        # the mark alone, brackets included
WORDMARK_IDS = {"wordmark-npy", "wordmark-quick", "tagline"}

ICON_SIZE = 512          # canvas of the application icon
PLATE_MARGIN = 20        # transparent margin around the plate
PLATE_RADIUS = 104       # corner radius of the plate
MARK_SCALE = 0.80        # mark width as a fraction of the plate width

ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
SMALL_ICON_MAX = 24      # .ico entries up to this size use the simplified icon


# ----------------------------------------------------------------------
# Building SVG documents
# ----------------------------------------------------------------------

def themed(master: ET.Element, theme: dict[str, str]) -> ET.Element:
    """Return a copy of the master's top-level group, recoloured for ``theme``."""
    group = copy.deepcopy(master.find(f"{{{SVG_NS}}}g"))
    for shape in group.iter():
        role = shape.attrib.pop("data-role", None)
        if role is None:
            continue
        if role.endswith("-stroke"):
            shape.set("stroke", theme[role.removesuffix("-stroke")])
        else:
            shape.set("fill", theme[role])
    return group


def themed_logo(master: ET.Element, theme: dict[str, str], with_wordmark: bool) -> ET.Element:
    """The logo recoloured for ``theme``, optionally without the wordmark."""
    logo = themed(master, theme)
    if not with_wordmark:
        for shape in [s for s in logo if s.get("id") in WORDMARK_IDS]:
            logo.remove(shape)
    return logo


def svg_document(content: ET.Element, view_box: tuple[float, float, float, float]) -> str:
    x, y, width, height = view_box
    root = ET.Element(
        f"{{{SVG_NS}}}svg",
        {"viewBox": f"{x:g} {y:g} {width:g} {height:g}", "width": f"{width:g}", "height": f"{height:g}"},
    )
    root.append(content)
    ET.indent(root)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + GENERATED_NOTE + ET.tostring(root, encoding="unicode") + "\n"


def app_icon_content(master: ET.Element) -> ET.Element:
    """The mark centred on a rounded plate, on an ICON_SIZE square canvas."""
    plate_side = ICON_SIZE - 2 * PLATE_MARGIN
    mark_x, mark_y, mark_width, mark_height = MARK_BOX
    scale = plate_side * MARK_SCALE / mark_width
    offset_x = (ICON_SIZE - mark_width * scale) / 2
    offset_y = (ICON_SIZE - mark_height * scale) / 2

    icon = ET.Element(f"{{{SVG_NS}}}g")
    ET.SubElement(icon, f"{{{SVG_NS}}}rect", {
        "x": str(PLATE_MARGIN), "y": str(PLATE_MARGIN),
        "width": str(plate_side), "height": str(plate_side),
        "rx": str(PLATE_RADIUS), "ry": str(PLATE_RADIUS),
        "fill": APP_ICON["plate"], "stroke": APP_ICON["plate-border"], "stroke-width": "2",
    })
    placed = ET.SubElement(icon, f"{{{SVG_NS}}}g", {
        "transform": f"translate({offset_x:.3f},{offset_y:.3f}) scale({scale:.5f}) "
                     f"translate({-mark_x:g},{-mark_y:g})",
    })
    placed.append(themed_logo(master, APP_ICON, with_wordmark=False))
    return icon


# ----------------------------------------------------------------------
# Rasterising
# ----------------------------------------------------------------------

def render_png(svg: str, size: int) -> QImage:
    """Render a square SVG at ``size`` pixels, supersampled for clean edges."""
    oversample = 4
    big = QImage(size * oversample, size * oversample, QImage.Format_ARGB32)
    big.fill(Qt.transparent)
    painter = QPainter(big)
    painter.setRenderHint(QPainter.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode("utf-8"))).render(painter, QRectF(0, 0, big.width(), big.height()))
    painter.end()
    return big.scaled(size, size, Qt.IgnoreAspectRatio, Qt.SmoothTransformation)


def png_bytes(image: QImage) -> bytes:
    buffer = QBuffer()
    buffer.open(QIODevice.WriteOnly)
    image.save(buffer, "PNG")
    return bytes(buffer.data())


def ico_bytes(images: list[QImage]) -> bytes:
    """Pack PNG-encoded images into an .ico file (PNG entries, Windows Vista+)."""
    payloads = [png_bytes(image) for image in images]
    header = struct.pack("<HHH", 0, 1, len(images))
    directory = b""
    offset = len(header) + 16 * len(images)
    for image, payload in zip(images, payloads):
        side = image.width() % 256          # 256 is stored as 0
        directory += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(payload), offset)
        offset += len(payload)
    return header + directory + b"".join(payloads)


# ----------------------------------------------------------------------

def write(path: str, data: str | bytes) -> None:
    target = REPO / path
    if isinstance(data, str):
        target.write_text(data, encoding="utf-8")
    else:
        target.write_bytes(data)
    print(f"  {path}  ({target.stat().st_size:,} bytes)")


def main() -> None:
    app = QGuiApplication([])  # noqa: F841 - Qt needs an application object to render
    master = ET.parse(MASTER).getroot()
    small_master = ET.parse(SMALL_MASTER).getroot()

    print("README logos and bare mark:")
    for name, theme in (("light", LIGHT), ("dark", DARK)):
        write(f"docs/assets/logo-horizontal-{name}.svg",
              svg_document(themed_logo(master, theme, with_wordmark=True), LOGO_BOX))
        write(f"docs/assets/icon-{name}.svg",
              svg_document(themed_logo(master, theme, with_wordmark=False), MARK_BOX))

    print("Application icon:")
    app_icon = svg_document(app_icon_content(master), (0, 0, ICON_SIZE, ICON_SIZE))
    write("src/npyquick/resources/icon.svg", app_icon)             # installed by --install-desktop
    write("packaging/appimage/npyquick.png", png_bytes(render_png(app_icon, 256)))
    write("packaging/appimage/npyquick-512.png", png_bytes(render_png(app_icon, 512)))
    write("snap/gui/npyquick.png", png_bytes(render_png(app_icon, 512)))

    small_icon = svg_document(themed(small_master, APP_ICON_SMALL), (0, 0, 16, 16))
    ico_images = [render_png(small_icon if size <= SMALL_ICON_MAX else app_icon, size) for size in ICO_SIZES]
    ico = ico_bytes(ico_images)
    write("packaging/windows/npyquick.ico", ico)            # embedded in the .exe by PyInstaller
    write("src/npyquick/resources/icon.ico", ico)           # loaded at startup as the window icon


if __name__ == "__main__":
    main()
